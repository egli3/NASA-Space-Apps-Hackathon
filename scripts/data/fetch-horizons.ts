/**
 * Reference planet positions from NASA JPL Horizons, used to validate the engine's Kepler solver.
 * Usage: npx tsx scripts/data/fetch-horizons.ts
 *
 * Asks Horizons for heliocentric ecliptic J2000 position vectors of Earth (399), Mars (499) and Jupiter (599)
 * every 3 months from 2026 to 2034 (the years our missions fly). Raw API responses go to data/raw/horizons/<id>.json,
 * and the parsed table to data/raw/horizons/validation.json, which src/engine/engine.test.ts checks the engine against.
 * Owner: Track B. The game never calls this service: positions in play come from the JPL approximate elements.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'data', 'raw', 'horizons');
const AU_KM = 149597870.7;
const BODIES = [
  { bodyId: 'earth', horizonsId: '399' },
  { bodyId: 'mars', horizonsId: '499' },
  { bodyId: 'jupiter', horizonsId: '599' },
];
const START = '2026-01-01', STOP = '2034-12-31', STEP = '3 mo';

interface Row { bodyId: string; horizonsId: string; date: string; jdTdb: number; xAU: number; yAU: number; zAU: number }

async function fetchBody(body: (typeof BODIES)[number]): Promise<Row[]> {
  const params: Record<string, string> = {
    format: 'json', COMMAND: `'${body.horizonsId}'`, OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'", EPHEM_TYPE: "'VECTORS'",
    CENTER: "'500@10'", REF_PLANE: "'ECLIPTIC'", REF_SYSTEM: "'ICRF'", START_TIME: `'${START}'`, STOP_TIME: `'${STOP}'`, STEP_SIZE: `'${STEP}'`,
    VEC_TABLE: "'2'", OUT_UNITS: "'KM-S'", CSV_FORMAT: "'YES'",
  };
  const url = 'https://ssd.jpl.nasa.gov/api/horizons.api?' + Object.entries(params).map(([k, v]) => `${k}=${encodeURIComponent(v)}`).join('&');
  const res = await fetch(url, { headers: { 'User-Agent': 'margin-game-data-script' } });
  if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
  const json = (await res.json()) as { result?: string; error?: string };
  if (!json.result) throw new Error(`Horizons error for ${body.horizonsId}: ${json.error ?? 'no result'}`);
  writeFileSync(join(DIR, `${body.horizonsId}.json`), JSON.stringify({ url, ...json }, null, 1) + '\n');
  const table = json.result.split('$$SOE')[1]?.split('$$EOE')[0];
  if (!table) throw new Error(`No ephemeris table for ${body.horizonsId}`);
  const rows: Row[] = [];
  for (const line of table.split('\n')) {
    const cols = line.split(',').map((c) => c.trim());
    if (cols.length < 5 || !cols[0]) continue;
    // JDTDB, "A.D. 2026-Jan-01 00:00:00.0000", X, Y, Z, VX, VY, VZ
    const jd = parseFloat(cols[0]);
    const date = new Date((jd - 2440587.5) * 86400000).toISOString().slice(0, 10);
    rows.push({ bodyId: body.bodyId, horizonsId: body.horizonsId, date, jdTdb: jd, xAU: parseFloat(cols[2]) / AU_KM, yAU: parseFloat(cols[3]) / AU_KM, zAU: parseFloat(cols[4]) / AU_KM });
  }
  console.log(`  ${body.bodyId} (${body.horizonsId}): ${rows.length} dates`);
  return rows;
}

async function main() {
  mkdirSync(DIR, { recursive: true });
  console.log('Fetching JPL Horizons vectors …');
  const rows: Row[] = [];
  for (const b of BODIES) rows.push(...(await fetchBody(b)));
  const out = {
    source: 'jpl-horizons',
    notes: `Heliocentric (500@10) ecliptic J2000 position vectors from the JPL Horizons API, ${START} to ${STOP}, step ${STEP}. Positions in AU (1 AU = ${AU_KM} km). Generated by scripts/data/fetch-horizons.ts.`,
    rows,
  };
  writeFileSync(join(DIR, 'validation.json'), JSON.stringify(out, null, 1) + '\n');
  console.log(`Wrote ${rows.length} rows to data/raw/horizons/validation.json`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
