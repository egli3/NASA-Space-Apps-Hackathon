/**
 * Snapshot of real space weather from NASA's DONKI database (CCMC), baked into src/data/space-weather.json.
 * Usage: npx tsx scripts/data/fetch-donki.ts            (fetch, save raw, rebuild the JSON)
 *        npx tsx scripts/data/fetch-donki.ts --offline  (rebuild the JSON from data/raw/donki/ without the network)
 *
 * What it keeps (DATA_PLAN §3.1): every M- and X-class solar flare and every solar energetic particle (SEP) event
 * from 2014-01-01 to 2019-12-31, the declining phase of Solar Cycle 24. The flight sim replays these on a
 * seed-shifted calendar (GAME_DESIGN §5.6). Raw responses are committed under data/raw/donki/ for provenance.
 * Owner: Track B. No API key is needed; the game itself never calls this service.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const RAW_DIR = join(ROOT, 'data', 'raw', 'donki');
const OUT = join(ROOT, 'src', 'data', 'space-weather.json');
const BASE = 'https://ccmc.gsfc.nasa.gov/DONKI/WS/get';
const YEARS = [2014, 2015, 2016, 2017, 2018, 2019];
const OFFLINE = process.argv.includes('--offline');

interface RawFlare { flrID: string; beginTime: string; peakTime: string | null; classType: string | null; link: string }
interface RawSep { sepID: string; eventTime: string; link: string }
interface Out { id: string; kind: 'FLR' | 'SEP'; time: string; classType?: string; severity: number; link?: string }

/** GAME_DESIGN §5.6: M1 = 0.30 rising linearly to M9.9 = 0.55; X1 = 0.60 rising linearly to X10 and above = 1.0. */
export function flareSeverity(classType: string): number | undefined {
  const m = /^([MX])(\d+(\.\d+)?)$/.exec(classType.trim().toUpperCase());
  if (!m) return undefined; // A, B and C class flares are too weak to matter to a spacecraft
  const mag = parseFloat(m[2]);
  const s = m[1] === 'M' ? 0.3 + ((Math.min(9.9, Math.max(1, mag)) - 1) / 8.9) * 0.25 : 0.6 + ((Math.min(10, Math.max(1, mag)) - 1) / 9) * 0.4;
  return Math.round(s * 1000) / 1000;
}
const SEP_SEVERITY = 0.8;

async function load<T>(kind: 'FLR' | 'SEP', year: number): Promise<T[]> {
  const file = join(RAW_DIR, `${kind}-${year}.json`);
  if (OFFLINE) return JSON.parse(readFileSync(file, 'utf8')) as T[];
  // The service refuses ranges longer than 60 days, so ask month by month and store one raw file per year.
  const data: T[] = [];
  for (let month = 1; month <= 12; month++) {
    const mm = String(month).padStart(2, '0');
    const lastDay = new Date(Date.UTC(year, month, 0)).getUTCDate();
    const url = `${BASE}/${kind}?startDate=${year}-${mm}-01&endDate=${year}-${mm}-${lastDay}`;
    const res = await fetch(url, { headers: { 'User-Agent': 'margin-game-data-script' } });
    if (!res.ok) throw new Error(`${url} → HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
    const text = await res.text();
    if (text.trim()) data.push(...(JSON.parse(text) as T[]));
    await new Promise((r) => setTimeout(r, 150)); // be polite to the service
  }
  writeFileSync(file, JSON.stringify(data, null, 1) + '\n');
  console.log(`  ${kind} ${year}: ${data.length} records`);
  return data;
}

async function main() {
  mkdirSync(RAW_DIR, { recursive: true });
  console.log(OFFLINE ? 'Rebuilding from data/raw/donki/ …' : `Fetching ${BASE} …`);
  const events: Out[] = [];
  let flaresSeen = 0, sepSeen = 0;
  for (const year of YEARS) {
    for (const f of await load<RawFlare>('FLR', year)) {
      flaresSeen++;
      const severity = f.classType ? flareSeverity(f.classType) : undefined;
      if (severity === undefined) continue;
      // keep the DONKI page link only for the storms strong enough to trigger a card (keeps the bundle small)
      events.push({ id: f.flrID, kind: 'FLR', time: f.peakTime ?? f.beginTime, classType: f.classType!.trim().toUpperCase(), severity, ...(severity >= 0.6 ? { link: f.link } : {}) });
    }
    // DONKI lists one SEP record per detecting instrument; the engine only needs one storm per start time.
    const seenSep = new Set<string>();
    for (const s of await load<RawSep>('SEP', year)) {
      sepSeen++;
      const day = s.eventTime.slice(0, 10);
      if (seenSep.has(day)) continue;
      seenSep.add(day);
      events.push({ id: s.sepID, kind: 'SEP', time: s.eventTime, severity: SEP_SEVERITY, link: s.link });
    }
  }
  events.sort((a, b) => (a.time < b.time ? -1 : a.time > b.time ? 1 : a.id < b.id ? -1 : 1));

  const count = (pred: (e: Out) => boolean) => events.filter(pred).length;
  const out = {
    sources: ['nasa-donki'],
    confidence: 'verified',
    notes:
      `Generated by scripts/data/fetch-donki.ts from ${BASE}/FLR and /SEP, 2014-01-01 to 2019-12-31 (raw responses in data/raw/donki/). ` +
      `Kept ${count((e) => e.kind === 'FLR' && e.classType!.startsWith('M'))} M-class and ${count((e) => e.kind === 'FLR' && e.classType!.startsWith('X'))} X-class flares ` +
      `out of ${flaresSeen} flare records, and ${count((e) => e.kind === 'SEP')} SEP days out of ${sepSeen} SEP records (one per detecting instrument; first record of each day kept). ` +
      'Times are flare peak times and SEP event times as reported. Severity is the game mapping of GAME_DESIGN §5.6 (M1 = 0.30 … M9.9 = 0.55, X1 = 0.60 … X10+ = 1.0, SEP = 0.8); the class and time are the real record.',
    events,
  };
  writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n');
  console.log(`Wrote ${events.length} events to src/data/space-weather.json (${(JSON.stringify(out).length / 1024).toFixed(0)} kB minified)`);
  const strongest = [...events].filter((e) => e.kind === 'FLR').sort((a, b) => b.severity - a.severity).slice(0, 5);
  console.log('Strongest flares:', strongest.map((e) => `${e.classType} ${e.time.slice(0, 10)}`).join(', '));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
